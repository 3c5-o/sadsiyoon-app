export function getStudyMaterials(): StudyMaterial[] {
  return STUDY_MATERIALS;
}

export function getStudyMaterialById(id: string): StudyMaterial | null {
  return STUDY_MATERIALS.find((m) => m.id === id) || null;
}

export function getStudyMaterialsBySubject(subject: string): StudyMaterial[] {
  return STUDY_MATERIALS.filter((m) => m.subject.includes(subject) || subject.includes(m.subject));
}

export function getStudyMaterialsByTeacher(teacherName: string): StudyMaterial[] {
  return STUDY_MATERIALS.filter((m) => m.teacherName.includes(teacherName) || teacherName.includes(m.teacherName));
}
